constexpr const LdpcTable* find_ldpc_table(int rate_num, int rate_den) {
    for (const LdpcTable& t : kLdpcTables) {
        if (t.rate_num == rate_num && t.rate_den == rate_den) return &t;
    }
    return nullptr;
}

